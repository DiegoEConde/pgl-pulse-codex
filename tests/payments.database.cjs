const fs = require("node:fs");
const assert = require("node:assert/strict");
const { randomUUID } = require("node:crypto");
const { PGlite } = require(process.env.PGL_PGLITE_PATH || process.env.TEMP + "/pandasoft-validation/node_modules/@electric-sql/pglite");
// Base efímera: ejecuta las migraciones reales sin conexión a Supabase.
(async () => {
 const db = new PGlite();
 try {
  await db.exec("CREATE ROLE anon; CREATE ROLE authenticated; CREATE SCHEMA auth; CREATE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql AS $$ SELECT '{}'::jsonb $$;");
  await db.exec("ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon,authenticated; ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO anon,authenticated;");
  const files=fs.readdirSync("supabase/migrations").filter(f=>f.endsWith(".sql")).sort();
  for(const file of files.filter(f=>f < "20260913000100_sale_installments.sql")) await db.exec(fs.readFileSync("supabase/migrations/"+file,"utf8"));
  await db.exec("SET ROLE anon");
  await db.exec("INSERT INTO producto(marca,nombre,categoria) VALUES('Test','Equipo','Test'); INSERT INTO proveedor(nombre) VALUES('Proveedor'); INSERT INTO cliente(nombre) VALUES('Cliente'); INSERT INTO vendedor(nombre,porcentaje_comision) VALUES('Vendedor',5);");
  const day=(await db.query("SELECT (now() at time zone 'America/Argentina/Buenos_Aires')::date::text AS day")).rows[0].day;
  const order=(await db.query("SELECT pgl_create_order(1,$1::date,$1::date,0,'', $2::jsonb,$3::uuid) AS id",[day,JSON.stringify([{producto_id:1,color:'Negro',cantidad:8,precio_costo_usd:10}]),randomUUID()])).rows[0].id;
  await db.query("SELECT pgl_order_status($1,'PEDIDO')",[order]);
  const line=(await db.query("SELECT id FROM detalle_pedido WHERE pedido_id=$1",[order])).rows[0].id;
  await db.query("SELECT pgl_receive_order($1,$2::jsonb)",[order,JSON.stringify(Array.from({length:8},()=>({detalle_id:line})))]);
  await db.query("SELECT pgl_create_sale(1,1,1,$1::date,100,5,true,$2::uuid)",[day,randomUUID()]);
  await db.query("SELECT pgl_create_sale(2,1,1,$1::date,100,5,false,$2::uuid)",[day,randomUUID()]);
  await db.exec("RESET ROLE");
  await db.exec(fs.readFileSync("supabase/migrations/20260913000100_sale_installments.sql","utf8"));
  for(const file of files.filter(f=>f > "20260913000100_sale_installments.sql")) await db.exec(fs.readFileSync("supabase/migrations/"+file,"utf8"));
  await db.exec("SET ROLE anon");
  const snapshot=async()=>(await db.query("SELECT pgl_snapshot() AS data")).rows[0].data;
  let data=await snapshot();
  assert.equal(data.units.find(u=>u.id===1).cobrado_inicial_usd,100);
  assert.equal(data.units.find(u=>u.id===2).cobrado_inicial_usd,0);
  assert.deepEqual(data.salePayments,[]);
  const create=(id,amount,delivered=false,request=randomUUID(),price=100)=>db.query("SELECT pgl_create_sale_partial($1,1,1,$2::date,$3,5,$4,$5::uuid,$6)",[id,day,price,amount,request,delivered]);
  const pay=(id,amount,request=randomUUID(),delivered=false)=>db.query("SELECT pgl_add_sale_payment($1,$2,$3::uuid,$4)",[id,amount,request,delivered]);
  const saleRequest=randomUUID();
  await create(3,40,false,saleRequest); await create(3,40,false,saleRequest);
  await assert.rejects(create(3,50,false,saleRequest),/reintento/);
  data=await snapshot(); assert.equal(data.salePayments.filter(p=>p.unidad_id===3).length,1);
  const paymentRequest=randomUUID(); await pay(3,40,paymentRequest); await pay(3,40,paymentRequest);
  data=await snapshot(); assert.equal(data.salePayments.filter(p=>p.unidad_id===3).reduce((n,p)=>n+p.importe_usd,0),80);
  await assert.rejects(pay(3,41,paymentRequest),/reintento/);
  await assert.rejects(pay(3,21),/supera/);
  await assert.rejects(pay(3,20),/retiro/);
  for(const invalid of [0,-1,0.001,null,'NaN']) await assert.rejects(pay(3,invalid),/importe/);
  const finalRequest=randomUUID(); await pay(3,20,finalRequest,true); await pay(3,20,finalRequest,true);
  data=await snapshot(); const sale=data.units.find(u=>u.id===3);
  assert.equal(sale.pago_verificado,true); assert.equal(sale.estado,'ENTREGADA'); assert.ok(sale.fecha_entrega);
  assert.deepEqual(data.salePayments.filter(p=>p.unidad_id===3).map(p=>p.importe_usd),[40,40,20]);
  await assert.rejects(pay(3,1),/supera/);
  await assert.rejects(create(4,101),/importe/);
  await assert.rejects(create(4,100),/retiro/);
  data=await snapshot(); assert.equal(data.units.find(u=>u.id===4).estado,'STOCK');
  await create(4,100,true);
  await create(5,0,false); await assert.rejects(pay(5,40,paymentRequest),/reintento/);
  await create(6,0,true,randomUUID(),0);
  await create(7,0.1,true,randomUUID(),0.3); await pay(7,0.2);
  await assert.rejects(db.exec("SELECT pgl_set_payment(3,false)"),/Actualizá/);
  await assert.rejects(db.query("SELECT pgl_create_sale(8,1,1,$1::date,100,5,false,$2::uuid)",[day,randomUUID()]),/Actualizá/);
  await assert.rejects(db.exec("UPDATE unidad SET pago_verificado=false WHERE id=3"),/permission denied/);
  await assert.rejects(db.exec("DELETE FROM venta_abono"),/permission denied/);
  await assert.rejects(db.query("SELECT pgl_create_sale_alpha(8,1,1,$1::date,100,5,false,$2::uuid)",[day,randomUUID()]),/permission denied/);
  // Compras: opciones persistentes, variantes del mismo modelo y atomicidad.
  assert.ok((await snapshot()).categoryCharacteristics.some(o=>o.clave==='rom'));
  const consoleId=(await db.query("INSERT INTO producto(marca,nombre,categoria) VALUES('Test','Consola','Consolas') RETURNING id")).rows[0].id;
  const purchaseLines=['Digital','Pro'].map(edicion=>({producto_id:consoleId,color:'',cantidad:1,precio_costo_usd:100,atributos:{edicion,rom:'1 TB'}}));
  const request=randomUUID();
  const purchase=async(lines= purchaseLines,token=request)=>(await db.query("SELECT pgl_create_order(1,$1::date,NULL,0,'Notas',$2::jsonb,$3::uuid) AS id",[day,JSON.stringify(lines),token])).rows[0].id;
  const purchaseId=await purchase();assert.equal(await purchase(),purchaseId);
  const orderData=(await snapshot()).orders.find(o=>o.id===purchaseId);
  assert.equal(orderData.fecha_estimada,null);assert.equal(orderData.costo_envio_usd,0);assert.equal(orderData.estado,'BORRADOR');
  assert.deepEqual((await snapshot()).lines.filter(l=>l.pedido_id===purchaseId).map(l=>l.atributos.edicion).sort(),['Digital','Pro']);
  assert.equal((await snapshot()).units.filter(u=>u.pedido_id===purchaseId).length,0);
  const before=(await snapshot()).orders.length;
  await assert.rejects(purchase([{...purchaseLines[0],atributos:{edicion:'Inexistente'}}],randomUUID()),/opción válida/);
  await assert.rejects(purchase([{...purchaseLines[0],atributos:{}}],randomUUID()),/opción válida/);
  await assert.rejects(purchase([purchaseLines[0],purchaseLines[0]],randomUUID()),/duplicate key/);
  assert.equal((await snapshot()).orders.length,before);
  console.log('Compras PostgreSQL: configuración, fecha nula, variantes, reintentos y atomicidad OK');
  // El resto del circuito continúa validándose con las RPC nuevas.
  await db.exec("RESET ROLE");
  await db.exec(fs.readFileSync("supabase/tests/integration.sql","utf8"));
  await db.exec(fs.readFileSync("supabase/tests/categories.sql","utf8"));
  console.log("B2 PostgreSQL: migración, saldos alpha, 40+40+20, reintentos, límites, retiro, atomicidad, permisos e integración OK");
 } finally { await db.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
