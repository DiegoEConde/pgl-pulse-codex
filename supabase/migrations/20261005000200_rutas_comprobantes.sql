CREATE OR REPLACE FUNCTION public.pgl_generate_orders(p_ids jsonb) RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE changed integer;
BEGIN
 IF jsonb_typeof(p_ids) IS DISTINCT FROM 'array' THEN RAISE EXCEPTION 'Selecciona pedidos validos'; END IF;
 IF EXISTS (
  SELECT 1 FROM public.pedido p
  WHERE p.estado='BORRADOR'
   AND p.id IN (SELECT value::bigint FROM jsonb_array_elements_text(p_ids))
   AND p.repartidor_id IS NULL
 ) THEN
  RAISE EXCEPTION 'Asigna un repartidor antes de generar pedidos';
 END IF;
 UPDATE public.pedido SET estado='PEDIDO'
 WHERE estado='BORRADOR' AND id IN (SELECT value::bigint FROM jsonb_array_elements_text(p_ids));
 GET DIAGNOSTICS changed = ROW_COUNT;
 RETURN changed;
END $$;

CREATE OR REPLACE FUNCTION public.pgl_set_sale_delivery(p_unit bigint,p_mode text,p_courier bigint) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE mode text:=upper(coalesce(nullif(trim(p_mode),''),'RETIRA_CLIENTE'));
BEGIN
 IF mode NOT IN ('REPARTIDOR','RETIRA_CLIENTE') THEN RAISE EXCEPTION 'Selecciona un modo de entrega valido'; END IF;
 IF mode='REPARTIDOR' THEN
  IF p_courier IS NULL OR NOT EXISTS(SELECT 1 FROM public.repartidor WHERE id=p_courier) THEN RAISE EXCEPTION 'Selecciona un repartidor existente'; END IF;
 ELSE
  IF p_courier IS NOT NULL THEN RAISE EXCEPTION 'El retiro del cliente no usa repartidor'; END IF;
 END IF;
 UPDATE public.unidad
 SET entrega_modo=mode,repartidor_id=CASE WHEN mode='REPARTIDOR' THEN p_courier ELSE NULL END
 WHERE id=p_unit AND estado IN ('REPARTO','ENTREGADA');
 IF NOT FOUND THEN RAISE EXCEPTION 'La unidad no tiene una venta activa'; END IF;
END $$;

